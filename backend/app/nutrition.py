# Единицы → граммы или миллилитры
MASS = {"г": 1.0, "гр": 1.0, "кг": 1000.0, "мг": 0.001}
VOLUME_ML = {"мл": 1.0, "л": 1000.0, "ч. л.": 5.0, "ст. л.": 15.0, "стакан": 200.0, "капля": 0.05}
PIECE = {"шт", "зубчик", "долька", "пучок", "головка", "банка", "пачка", "порция", "горсть"}
NEGLIGIBLE = {"по вкусу", "щепотка"}


def _norm(name: str) -> str:
    s = name.lower().replace("ё", "е").strip()
    s = re.sub(r"[«»\"“”()%]", " ", s)
    return " ".join(s.split())


_SEED_NORM = {_norm(k): v for k, v in SEED.items()}


def seed_for(name: str):
    """Ищет продукт во встроенном справочнике: точное совпадение, затем по первым словам.
    «Сливочное масло 82%» → «сливочное масло», «Мука пшеничная в/с» → «мука пшеничная»."""
    words = _norm(name).split()
    for n in range(len(words), 0, -1):
        key = " ".join(words[:n])
        if key in _SEED_NORM:
            return _SEED_NORM[key]
    return None


def fill_from_seed(product) -> bool:  # noqa: ANN001
    """Заполняет пустые КБЖУ продукта из справочника. True — если что-то заполнили."""
    if product.kcal is not None:
        return False
    seed = seed_for(product.name)
    if not seed:
        return False
    product.kcal, product.protein, product.fat, product.carbs, piece, density = seed
    if product.piece_grams is None:
        product.piece_grams = piece
    if product.density is None:
        product.density = density
    product.nutrition_source = "auto"
    return True


# ---------------- расчёт рецепта ----------------
def grams(amount: float | None, unit: str, product) -> float | None:  # noqa: ANN001
    """Количество ингредиента в граммах; None — посчитать нельзя."""
    unit = (unit or "").strip()
    if unit in NEGLIGIBLE:
        return 0.0
    if amount is None:
        return None
    if unit in MASS:
        return amount * MASS[unit]
    if unit in VOLUME_ML:
        return amount * VOLUME_ML[unit] * (product.density or 1.0)
    if unit in PIECE or unit == "":
        return amount * product.piece_grams if product.piece_grams else None
    return None


@dataclass
class Nutrition:
    kcal: float = 0
    protein: float = 0
    fat: float = 0
    carbs: float = 0
    weight: float = 0
    counted: int = 0
    missing: list[str] = field(default_factory=list)


def recipe_nutrition(ingredients) -> Nutrition:  # noqa: ANN001
    total = Nutrition()
    for ing in ingredients:
        p = ing.product
        g = grams(ing.amount, ing.unit, p)
        if g is None or p.kcal is None:
            if ing.unit not in NEGLIGIBLE:
                total.missing.append(p.name)
            continue
        k = g / 100
        total.kcal += (p.kcal or 0) * k
        total.protein += (p.protein or 0) * k
        total.fat += (p.fat or 0) * k
        total.carbs += (p.carbs or 0) * k
        total.weight += g
        total.counted += 1
    total.missing = list(dict.fromkeys(total.missing))
    return total
